import { readdir, readFile, writeFile } from 'node:fs/promises';
import { cssMin } from 'jsda-kit/node/cssMin.js';
import { compileUtilities } from '../src/markup/styles.js';
import { listTemplates, loadTemplate } from '../src/templates/catalog.js';
import { join } from 'node:path';

for (let entry of await listTemplates()) {
  let template = await loadTemplate(entry.id);
  let chunks = [];
  for (let path of await readdir(template.assetsPath, {
    recursive: true,
  })) {
    if (/\.html?$/.test(path)) { chunks.push(await readFile(join(template.assetsPath, path), 'utf8')); }
  }
  let css = cssMin(await compileUtilities(chunks));
  await writeFile(join(template.assetsPath, 'styles.css'), `/* Generated by npm run templates:styles. */\n${css}\n`);
}
