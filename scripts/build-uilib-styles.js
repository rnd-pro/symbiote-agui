import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { compile } from '@tailwindcss/node';
import { cssMin } from 'jsda-kit/node/cssMin.js';
import { analyzeMarkup } from '../src/markup/analyze.js';
import { UILIB_TEMPLATES, UILIB_STATE_CLASSES } from '../uilib/templates.js';

let library = new URL('../uilib/', import.meta.url);
let output = new URL('dist/', library);
let registry = await readFile(new URL('index.js', library), 'utf8');
// Registration is the authoritative tag list; no second component inventory.
let registrations = [
  ...registry.matchAll(/\.reg\('(agui-[\w-]+)'\)/g),
];
let tags = [
  ...new Set(registrations.map((match) => match[1])),
].sort();
if (!tags.length) { throw new Error('No library component registrations found.'); }
let classes = [
  ...analyzeMarkup(Object.values(UILIB_TEMPLATES).join('\n')).classes,
  ...UILIB_STATE_CLASSES,
];
let sources = {
  'styles.css': `
    @layer theme, base, components, utilities;
    @import 'tailwindcss/theme.css' layer(theme);
    @import './tokens.css';
    @scope (${tags.join(', ')}) {
      @import 'tailwindcss/preflight.css' layer(base);
      @import './shared/styles.css';
      @layer base {
        :scope {
          color-scheme: var(--agui-color-scheme);
        }
      }
      @layer utilities { @tailwind utilities; }
    }
  `,
  'page.css': `
    @layer theme, base, components, utilities;
    @import 'tailwindcss/preflight.css' layer(base);
    @import './page.css';
  `,
};

await mkdir(output, {
  recursive: true,
});
for (let [
  name,
  source,
] of Object.entries(sources)) {
  let compiler = await compile(source, {
    base: fileURLToPath(library),
    onDependency() {},
  });
  let css = cssMin(compiler.build(classes));
  await writeFile(new URL(name, output), `/* Generated by npm run uilib:styles. */\n${css}\n`);
  process.stderr.write(`${name}: ${Buffer.byteLength(css)} bytes\n`);
}
